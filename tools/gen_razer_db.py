"""Generates synaptix/razer/db.py from the OpenRGB sources.

OpenRGB (GPL-2.0-or-later) keeps the most complete table of Razer devices:
product IDs, matrix types, transaction IDs, LED layouts and the HID interface
that accepts lighting reports. This script converts that table to Python so
it can be refreshed when OpenRGB adds devices.

Usage: python3 tools/gen_razer_db.py /path/to/OpenRGB > synaptix/razer/db.py
"""

import os
import re
import subprocess
import sys

root = sys.argv[1]
razer_dir = os.path.join(root, "Controllers", "RazerController")


def read(*parts):
    with open(os.path.join(razer_dir, *parts), encoding="utf-8") as f:
        return f.read()


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


header = read("RazerDevices.h")
pid_macros = {name: int(value, 16) for name, value in
              re.findall(r"#define\s+(RAZER_\w+_PID)\s+(0x[0-9A-Fa-f]+)", header)}

devices_cpp = strip_comments(read("RazerDevices.cpp"))

zones = {}
for name, body in re.findall(r"static const razer_zone\s+(\w+)\s*=\s*\{(.*?)\};", devices_cpp, re.S):
    fields = [f.strip() for f in body.split(",")]
    label = fields[0]
    label = label.strip('"') if label.startswith('"') else label.replace("ZONE_EN_", "").title()
    zones[name] = (label, fields[1].replace("ZONE_TYPE_", "").lower(), int(fields[2]), int(fields[3]))

DEVICE_RE = re.compile(
    r"static const razer_device\s+(\w+)\s*=\s*\{\s*"
    r'"([^"]+)"\s*,\s*(\w+)\s*,\s*DEVICE_TYPE_(\w+)\s*,\s*RAZER_MATRIX_TYPE_(\w+)\s*,\s*'
    r"(0x[0-9A-Fa-f]+|\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*\{(.*?)\}", re.S)

devices = {}
for var, name, pid_macro, dev_type, matrix, tid, rows, cols, zone_refs in DEVICE_RE.findall(devices_cpp):
    zone_list = [zones[z.strip().lstrip("&")] for z in zone_refs.split(",") if z.strip() not in ("", "NULL")]
    devices[var] = dict(name=name, pid=pid_macros[pid_macro], type=dev_type.lower(), matrix=matrix.lower(),
                        transaction_id=int(tid, 0), rows=int(rows), cols=int(cols), zones=zone_list)

list_body = re.search(r"razer_device_list\[\]\s*=\s*\{(.*?)\};", devices_cpp, re.S).group(1)
listed = [d.strip().lstrip("&") for d in list_body.split(",") if d.strip()]

# HID interface / usage page / usage accepted by DetectRazerControllers
detect_cpp = strip_comments(read("RazerControllerDetect.cpp"))
detectors: dict[int, list] = {}
for macro, args in re.findall(r"REGISTER_HID_DETECTOR_(IPU|PU)\s*\((.*?)\);", detect_cpp, re.S):
    parts = [p.strip() for p in re.sub(r'"[^"]*"', '"x"', args).split(",")]
    if parts[1] != "DetectRazerControllers" or parts[2] != "RAZER_VID":
        continue
    pid = pid_macros[parts[3]]
    if macro == "IPU":
        interface, page, usage = (int(v, 16) for v in parts[4:7])
    else:
        interface, page, usage = None, *(int(v, 16) for v in parts[4:6])
    detectors.setdefault(pid, [])
    if (interface, page, usage) not in detectors[pid]:
        detectors[pid].append((interface, page, usage))

controller_cpp = strip_comments(read("RazerController", "RazerController.cpp"))


def function_body(name):
    start = controller_cpp.index(f"RazerController::{name}(")
    end = controller_cpp.index("\n}\n", start)
    return controller_cpp[start:end]


def cases_before(text, marker):
    """PIDs of the case labels that fall through to the statement `marker`."""
    end = text.index(marker)
    block_start = text.rfind("break;", 0, end)
    block_start = text.rfind("switch", 0, end) if block_start == -1 else block_start
    return sorted(pid_macros[m] for m in re.findall(r"case\s+(RAZER_\w+_PID)\s*:", text[block_start:end]))


ctor = function_body("RazerController")
pid_sets = {
    "REPORT_ID_7": cases_before(ctor, "report_index    = 0x07"),
    "SOFTWARE_MODE_ON_OPEN": cases_before(ctor, "razer_set_device_mode(RAZER_DEVICE_MODE_SOFTWARE)"),
    "LED_ID_ZERO": cases_before(ctor, "dev_led_id = RAZER_LED_ID_ZERO"),
    "KEEPALIVE": cases_before(ctor, "keepalive_thread_run = true"),
    "MAX_BRIGHTNESS_100": cases_before(function_body("GetMaxBrightness"), "max_brightness = 100"),
    "NO_HARDWARE_BREATHING": cases_before(function_body("SupportsBreathing"), "supports_breathing = false"),
    "WAVE": cases_before(function_body("SupportsWave"), "supports_wave = true"),
}

commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"],
                        capture_output=True, text=True).stdout.strip() or "unknown"

out = sys.stdout
out.write(f'''"""Razer device table generated by tools/gen_razer_db.py from OpenRGB {commit}.

Do not edit by hand. Source: https://gitlab.com/CalcProgrammer1/OpenRGB
(Controllers/RazerController), licensed GPL-2.0-or-later.
"""

# pid: (name, type, matrix type, transaction id, rows, cols, ((zone, kind, rows, cols), ...))
DEVICES = {{
''')
seen = set()
for var in listed:
    d = devices[var]
    if d["pid"] in seen:
        continue
    seen.add(d["pid"])
    zone_text = "".join(f"({z[0]!r}, {z[1]!r}, {z[2]}, {z[3]}), " for z in d["zones"])
    out.write(f'    0x{d["pid"]:04X}: ({d["name"]!r}, {d["type"]!r}, {d["matrix"]!r}, 0x{d["transaction_id"]:02X}, '
              f'{d["rows"]}, {d["cols"]}, ({zone_text})),\n')
out.write("}\n\n# pid: ((interface or None, usage page, usage), ...)\nINTERFACES = {\n")
for pid in sorted(detectors):
    entries = ", ".join(f"({'None' if i is None else i}, 0x{p:02X}, 0x{u:02X})" for i, p, u in detectors[pid])
    out.write(f"    0x{pid:04X}: ({entries},),\n")
out.write("}\n")
for name, pids in pid_sets.items():
    out.write(f"\n{name} = frozenset({{\n")
    for i in range(0, len(pids), 8):
        out.write("    " + ", ".join(f"0x{p:04X}" for p in pids[i:i + 8]) + ",\n")
    out.write("})\n")
